// Imports the Flappy Duck art from a flappy-duck-frontend checkout into game/art.cjs and game/duck-frames.cjs.
// An authoring step, not part of the build: it needs ImageMagick (`magick`) and `cwebp` on PATH.
//   node scripts/import-duck-art.mjs ../flappy-duck-frontend
import { execFileSync } from "node:child_process"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("../", import.meta.url))
const source = process.argv[2]
if (!source) throw new Error("Usage: node scripts/import-duck-art.mjs <flappy-duck-frontend checkout>")
const sprites = path.join(source, "src/game/sprites")
const work = mkdtempSync(path.join(tmpdir(), "flappy-duck-art-"))
const magick = (...args) => execFileSync("magick", args, { maxBuffer: 1 << 28 })

// The duck is one still frame of the sheet, its eyes open and looking ahead; everything that moves
// (tilt, propeller, speed lines) the renderers animate around it, so it never drifts off its collider.
const SOURCE_FRAME = 0
const FRAME = 128
// Measured on that frame, in its pixels: the middle of the fuselage, where the duck collides and turns,
// and the hub of the propeller with the length of its blade.
const CENTER = [64, 67]
const HUB = [119.5, 56.5]
const BLADE = 48
// Pre-tilted rasters for surfaces without rotation: SPAN sprite pixels around CENTER, RASTER pixels across.
const SPAN = 160
const RASTER = 64
const ANGLES = Array.from({ length: 15 }, (_, index) => -15 + index * 7.5)
const RUN_TOLERANCE = 18

try {
  magick(path.join(sprites, "bird.png"), "-crop", "8x8@", "+repage", "+adjoin", path.join(work, "frame-%02d.png"))
  const still = path.join(work, "duck.png")
  const raw = clean(magick(path.join(work, `frame-${String(SOURCE_FRAME).padStart(2, "0")}.png`), "-depth", "8", "rgba:-"))
  writeFileSync(path.join(work, "duck.rgba"), raw)
  magick("-size", `${FRAME}x${FRAME}`, "-depth", "8", `rgba:${path.join(work, "duck.rgba")}`, still)
  execFileSync("cwebp", ["-quiet", "-q", "95", "-alpha_q", "100", "-m", "6", still, "-o", path.join(work, "duck.webp")])
  const sprite = readFileSync(path.join(work, "duck.webp")).toString("base64")

  const tilted = ANGLES.map((angle) => encodeFrame(magick(
    still, "-background", "none", "-virtual-pixel", "transparent",
    "-define", `distort:viewport=${SPAN}x${SPAN}+0+0`, "-distort", "SRT", `${CENTER[0]},${CENTER[1]} 1 ${angle} ${SPAN / 2},${SPAN / 2}`,
    "-filter", "Lanczos", "-resize", `${RASTER}x${RASTER}`, "-depth", "8", "rgba:-",
  ), RASTER))

  const city = ["big-city", "small-city"].map((name) => silhouette(path.join(sprites, "city/light", `${name}.png`)))
  const clouds = cloudBand()

  const write = (file, values) => writeFileSync(path.join(root, file), `"use strict"\n// Generated by scripts/import-duck-art.mjs from the Flappy Duck art. Regenerate instead of editing.\n${Object.entries(values).map(([name, value]) => `const ${name} = ${JSON.stringify(value)}`).join("\n")}\n\nmodule.exports = { ${Object.keys(values).join(", ")} }\n`)
  write("game/art.cjs", {
    DUCK: { src: `data:image/webp;base64,${sprite}`, size: FRAME, center: CENTER, hub: HUB, blade: BLADE },
    CITY: city,
    CLOUDS: clouds,
  })
  // Only the surfaces that cannot rotate an image need these, so they stay out of the Canvas bundles.
  write("game/duck-frames.cjs", { DUCK_FRAMES: { size: RASTER, span: SPAN, angles: ANGLES, frames: tilted } })
  console.log(`game/art.cjs: duck ${sprite.length} base64 characters, ${tilted.length} tilted rasters, ${city.length} city layers, ${clouds.shapes.length} clouds`)
} finally {
  rmSync(work, { recursive: true, force: true })
}

// Frame RGBA without the sheet's baked speed lines: where they cross the lower wing they are thin bright
// bands between matching wing colours, painted over from above and below; elsewhere they are what does
// not connect to the duck through fairly opaque pixels.
function clean(source) {
  const raw = Buffer.from(source)
  const at = (x, y) => (y * FRAME + x) * 4
  const lightness = (offset) => raw[offset] + raw[offset + 1] + raw[offset + 2]
  for (let x = 0; x < FRAME; x++) {
    for (let y = 86; y < FRAME - 1; y++) {
      const above = at(x, y - 1)
      if (raw[above + 3] < 250) continue
      let end = y
      while (end < FRAME - 1 && end - y < 6 && raw[at(x, end) + 3] > 200 && lightness(at(x, end)) > lightness(above) + 45) end++
      if (end === y || end - y > 5) continue
      const below = at(x, end)
      if (raw[below + 3] < 250 || Math.abs(lightness(below) - lightness(above)) > 60) continue
      for (let row = y; row < end; row++) {
        const t = (row - y + 1) / (end - y + 1)
        for (let channel = 0; channel < 3; channel++) raw[at(x, row) + channel] = Math.round(raw[above + channel] * (1 - t) + raw[below + channel] * t)
        raw[at(x, row) + 3] = 255
      }
      y = end
    }
  }
  const keep = new Uint8Array(FRAME * FRAME)
  const stack = [[FRAME / 2, FRAME / 2]]
  while (stack.length) {
    const [x, y] = stack.pop()
    if (x < 0 || y < 0 || x >= FRAME || y >= FRAME || keep[y * FRAME + x] || raw[at(x, y) + 3] <= 110) continue
    keep[y * FRAME + x] = 1
    for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) stack.push([x + dx, y + dy])
  }
  for (let y = 0; y < FRAME; y++) {
    for (let x = 0; x < FRAME; x++) {
      if (keep[y * FRAME + x]) continue
      const edge = [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => keep[(y + dy) * FRAME + x + dx] && x + dx >= 0 && x + dx < FRAME && y + dy >= 0 && y + dy < FRAME)
      const offset = at(x, y)
      // Below the body a pale, see-through pixel can only be what is left of a speed line.
      if (!edge || (y > 86 && raw[offset + 3] < 200 && raw[offset] > 110)) raw.writeUInt32BE(0, offset)
    }
  }
  return raw
}

// A raster as rows of runs: neighbouring opaque pixels merge while they stay within
// RUN_TOLERANCE of their mean, so flat shading costs one run; partly transparent edge pixels keep
// their alpha to be mixed with whatever lies behind them.
// A row is a string of tokens: `.` + base-36 length (transparent), base-36 length + hex colour (opaque),
// `!` + two hex digits of alpha + hex colour (one edge pixel).
function encodeFrame(raw, size) {
  const hex = (rgb) => rgb.map((value) => Math.round(value).toString(16).padStart(2, "0")).join("")
  const result = []
  for (let y = 0; y < size; y++) {
    let tokens = ""
    let run
    const flush = () => {
      if (!run) return
      const mean = run.sum.map((value) => value / run.pixels.length)
      for (let left = run.pixels.length; left > 0; left -= 35) tokens += Math.min(35, left).toString(36) + hex(mean)
      run = undefined
    }
    let clear = 0
    const flushClear = () => {
      for (; clear > 0; clear -= 35) tokens += "." + Math.min(35, clear).toString(36)
      clear = 0
    }
    for (let x = 0; x < size; x++) {
      const offset = (y * size + x) * 4
      const alpha = raw[offset + 3]
      const pixel = [raw[offset], raw[offset + 1], raw[offset + 2]]
      if (alpha < 16) {
        flush()
        clear++
        continue
      }
      flushClear()
      if (alpha < 240) {
        flush()
        tokens += "!" + alpha.toString(16).padStart(2, "0") + hex(pixel)
        continue
      }
      if (run) {
        const pixels = [...run.pixels, pixel]
        const mean = run.sum.map((value, channel) => (value + pixel[channel]) / pixels.length)
        if (pixels.every((sample) => sample.every((value, channel) => Math.abs(value - mean[channel]) <= RUN_TOLERANCE))) {
          run.pixels = pixels
          run.sum = run.sum.map((value, channel) => value + pixel[channel])
          continue
        }
        flush()
      }
      run = { pixels: [pixel], sum: [...pixel] }
    }
    flush()
    result.push(tokens)
  }
  return result
}

// Douglas–Peucker on a polyline of [x, y] points.
function simplify(points, tolerance) {
  if (points.length < 3) return points
  const [ax, ay] = points[0]
  const [bx, by] = points[points.length - 1]
  const length = Math.hypot(bx - ax, by - ay) || 1
  let worst = 0
  let index = 0
  for (let at = 1; at < points.length - 1; at++) {
    const [px, py] = points[at]
    const distance = Math.abs((by - ay) * px - (bx - ax) * py + bx * ay - by * ax) / length
    if (distance > worst) {
      worst = distance
      index = at
    }
  }
  if (worst <= tolerance) return [points[0], points[points.length - 1]]
  return [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)]
}

// The skyline of an opaque-on-transparent strip as a closed outline, top edge first.
function outline(raw, width, height, tolerance) {
  const tops = []
  for (let x = 0; x < width; x++) {
    let y = 0
    while (y < height && raw[y * width + x] < 128) y++
    tops.push(y)
  }
  const points = []
  for (let x = 0; x < width; x++) {
    if (x > 0 && tops[x] !== tops[x - 1]) points.push([x, tops[x - 1]])
    points.push([x, tops[x]])
  }
  points.push([width, tops[width - 1]])
  return simplify(points, tolerance).map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10])
}

function silhouette(file) {
  const [width, height] = magick(file, "-format", "%w %h", "info:").toString().split(" ").map(Number)
  const color = magick(file, "-alpha", "off", "-crop", `1x1+${Math.floor(width / 2)}+${height - 2}`, "-format", "#%[hex:p{0,0}]", "info:").toString().slice(0, 7).toLowerCase()
  const mask = magick(file, "-alpha", "extract", "-depth", "8", "gray:-")
  return { width, height, color, points: outline(mask, width, height, 0.6).flat() }
}

// A seamless strip of the game's clouds over a solid band, as Flappy Duck lays them out: each cloud
// rises two fifths of its height above the band's top.
function cloudBand() {
  const width = 660
  const top = 32
  const height = 110
  const placed = [[0, 0], [132, 5], [262, 2], [400, 7], [530, 4]]
  const shapes = placed.map(([x, variant]) => {
    const svg = readFileSync(path.join(sprites, "clouds", `cloud${variant}.svg`), "utf8")
    const [, , w, h] = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number)
    return { d: svg.match(/ d="([^"]+)"/)[1], x, y: top - h / 2.5, w, h }
  })
  const copies = shapes.flatMap((shape) => [-width, 0, width].map((offset) => ({ ...shape, x: shape.x + offset })))
  const tile = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">`
    + copies.map((shape) => `<path transform="translate(${shape.x} ${shape.y})" d="${shape.d}" fill="#fff"/>`).join("")
    + `<rect y="${top}" width="${width}" height="${height - top}" fill="#fff"/></svg>`
  const file = path.join(work, "clouds.svg")
  writeFileSync(file, tile)
  const mask = magick("-background", "none", file, "-alpha", "extract", "-depth", "8", "gray:-")
  return { width, height, top, shapes, points: outline(mask, width, height, 0.5).flat() }
}
