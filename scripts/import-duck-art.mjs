// Imports the Flappy Duck art from a flappy-duck-frontend checkout into game/art.cjs.
// An authoring step, not part of the build: it needs ImageMagick (`magick`) and `cwebp` on PATH.
//   node scripts/import-duck-art.mjs ../flappy-duck-frontend
import { execFileSync } from "node:child_process"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("../", import.meta.url))
const source = process.argv[2]
if (!source) throw new Error("Usage: node scripts/import-duck-art.mjs <flappy-duck-frontend checkout>")
const sprites = path.join(source, "src/game/sprites")
const work = mkdtempSync(path.join(tmpdir(), "flappy-duck-art-"))
const magick = (...args) => execFileSync("magick", args, { maxBuffer: 1 << 28 })

const SHEET_FRAMES = 32
const SHEET_FRAME = 128
const PIXEL_FRAMES = 8
const PIXEL_SIZE = 52
const RUN_TOLERANCE = 18

try {
  magick(path.join(sprites, "bird.png"), "-crop", "8x8@", "+repage", "+adjoin", path.join(work, "frame-%02d.png"))
  const frame = (index) => path.join(work, `frame-${String(index).padStart(2, "0")}.png`)

  // Every other frame of the 64-frame sheet keeps its loop length at half the frame rate.
  const rows = []
  for (let row = 0; row < SHEET_FRAMES / 8; row++) {
    const file = path.join(work, `row-${row}.png`)
    const frames = Array.from({ length: 8 }, (_, column) => frame((row * 8 + column) * (64 / SHEET_FRAMES)))
    magick(...frames, "-resize", `${SHEET_FRAME}x${SHEET_FRAME}`, "+append", file)
    rows.push(file)
  }
  magick(...rows, "-background", "none", "-append", path.join(work, "sheet.png"))
  execFileSync("cwebp", ["-quiet", "-q", "82", "-alpha_q", "90", "-m", "6", path.join(work, "sheet.png"), "-o", path.join(work, "sheet.webp")])
  const sheet = readFileSync(path.join(work, "sheet.webp")).toString("base64")

  const pixelFrames = Array.from({ length: PIXEL_FRAMES }, (_, index) => encodeFrame(frame(index * (64 / PIXEL_FRAMES))))

  const city = ["big-city", "small-city"].map((name) => silhouette(path.join(sprites, "city/light", `${name}.png`)))
  const clouds = cloudBand()

  const art = {
    DUCK_SHEET: { src: `data:image/webp;base64,${sheet}`, frame: SHEET_FRAME, columns: 8, frames: SHEET_FRAMES, fps: 9 },
    DUCK_FRAMES: { size: PIXEL_SIZE, fps: 9, frames: pixelFrames },
    CITY: city,
    CLOUDS: clouds,
  }
  const body = Object.entries(art).map(([name, value]) => `const ${name} = ${JSON.stringify(value)}`).join("\n")
  writeFileSync(path.join(root, "game/art.cjs"), `"use strict"\n// Generated by scripts/import-duck-art.mjs from the Flappy Duck art. Regenerate instead of editing.\n${body}\n\nmodule.exports = { ${Object.keys(art).join(", ")} }\n`)
  console.log(`game/art.cjs: sheet ${sheet.length} base64 characters, ${pixelFrames.length} pixel frames, ${city.length} city layers, ${clouds.shapes.length} clouds`)
} finally {
  rmSync(work, { recursive: true, force: true })
}

// One frame at PIXEL_SIZE as rows of runs: neighbouring opaque pixels merge while they stay within
// RUN_TOLERANCE of their mean, so flat shading costs one run; partly transparent edge pixels keep
// their alpha to be mixed with whatever lies behind them.
// A row is a string of tokens: `.` + base-36 length (transparent), base-36 length + hex colour (opaque),
// `!` + two hex digits of alpha + hex colour (one edge pixel).
function encodeFrame(file) {
  const size = PIXEL_SIZE
  const raw = magick(file, "-filter", "Lanczos", "-resize", `${size}x${size}`, "-depth", "8", "rgba:-")
  const hex = (rgb) => rgb.map((value) => Math.round(value).toString(16).padStart(2, "0")).join("")
  const result = []
  for (let y = 0; y < size; y++) {
    let tokens = ""
    let run
    const flush = () => {
      if (!run) return
      const mean = run.sum.map((value) => value / run.pixels.length)
      for (let left = run.pixels.length; left > 0; left -= 35) tokens += Math.min(35, left).toString(36) + hex(mean)
      run = undefined
    }
    let clear = 0
    const flushClear = () => {
      for (; clear > 0; clear -= 35) tokens += "." + Math.min(35, clear).toString(36)
      clear = 0
    }
    for (let x = 0; x < size; x++) {
      const offset = (y * size + x) * 4
      const alpha = raw[offset + 3]
      const pixel = [raw[offset], raw[offset + 1], raw[offset + 2]]
      if (alpha < 16) {
        flush()
        clear++
        continue
      }
      flushClear()
      if (alpha < 240) {
        flush()
        tokens += "!" + alpha.toString(16).padStart(2, "0") + hex(pixel)
        continue
      }
      if (run) {
        const pixels = [...run.pixels, pixel]
        const mean = run.sum.map((value, channel) => (value + pixel[channel]) / pixels.length)
        if (pixels.every((sample) => sample.every((value, channel) => Math.abs(value - mean[channel]) <= RUN_TOLERANCE))) {
          run.pixels = pixels
          run.sum = run.sum.map((value, channel) => value + pixel[channel])
          continue
        }
        flush()
      }
      run = { pixels: [pixel], sum: [...pixel] }
    }
    flush()
    result.push(tokens)
  }
  return result
}

// Douglas–Peucker on a polyline of [x, y] points.
function simplify(points, tolerance) {
  if (points.length < 3) return points
  const [ax, ay] = points[0]
  const [bx, by] = points[points.length - 1]
  const length = Math.hypot(bx - ax, by - ay) || 1
  let worst = 0
  let index = 0
  for (let at = 1; at < points.length - 1; at++) {
    const [px, py] = points[at]
    const distance = Math.abs((by - ay) * px - (bx - ax) * py + bx * ay - by * ax) / length
    if (distance > worst) {
      worst = distance
      index = at
    }
  }
  if (worst <= tolerance) return [points[0], points[points.length - 1]]
  return [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)]
}

// The skyline of an opaque-on-transparent strip as a closed outline, top edge first.
function outline(raw, width, height, tolerance) {
  const tops = []
  for (let x = 0; x < width; x++) {
    let y = 0
    while (y < height && raw[y * width + x] < 128) y++
    tops.push(y)
  }
  const points = []
  for (let x = 0; x < width; x++) {
    if (x > 0 && tops[x] !== tops[x - 1]) points.push([x, tops[x - 1]])
    points.push([x, tops[x]])
  }
  points.push([width, tops[width - 1]])
  return simplify(points, tolerance).map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10])
}

function silhouette(file) {
  const [width, height] = magick(file, "-format", "%w %h", "info:").toString().split(" ").map(Number)
  const color = magick(file, "-alpha", "off", "-crop", `1x1+${Math.floor(width / 2)}+${height - 2}`, "-format", "#%[hex:p{0,0}]", "info:").toString().slice(0, 7).toLowerCase()
  const mask = magick(file, "-alpha", "extract", "-depth", "8", "gray:-")
  return { width, height, color, points: outline(mask, width, height, 0.6).flat() }
}

// A seamless strip of the game's clouds over a solid band, as Flappy Duck lays them out: each cloud
// rises two fifths of its height above the band's top.
function cloudBand() {
  const width = 660
  const top = 32
  const height = 110
  const placed = [[0, 0], [132, 5], [262, 2], [400, 7], [530, 4]]
  const shapes = placed.map(([x, variant]) => {
    const svg = readFileSync(path.join(sprites, "clouds", `cloud${variant}.svg`), "utf8")
    const [, , w, h] = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number)
    return { d: svg.match(/ d="([^"]+)"/)[1], x, y: top - h / 2.5, w, h }
  })
  const copies = shapes.flatMap((shape) => [-width, 0, width].map((offset) => ({ ...shape, x: shape.x + offset })))
  const tile = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">`
    + copies.map((shape) => `<path transform="translate(${shape.x} ${shape.y})" d="${shape.d}" fill="#fff"/>`).join("")
    + `<rect y="${top}" width="${width}" height="${height - top}" fill="#fff"/></svg>`
  const file = path.join(work, "clouds.svg")
  writeFileSync(file, tile)
  const mask = magick("-background", "none", file, "-alpha", "extract", "-depth", "8", "gray:-")
  return { width, height, top, shapes, points: outline(mask, width, height, 0.5).flat() }
}
