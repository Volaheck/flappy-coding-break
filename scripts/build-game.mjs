import { readFile, writeFile, mkdir } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import path from "node:path"

const root = fileURLToPath(new URL("../", import.meta.url))
const modules = ["constants", "core", "canvas", "i18n"]
const sources = await Promise.all(modules.map(async (name) => {
  const source = await readFile(path.join(root, "game", `${name}.cjs`), "utf8")
  return `${JSON.stringify(`./${name}.cjs`)}: (module, exports, require) => {\n${source}\n}`
}))
const bundle = `// Generated by scripts/build-game.mjs. Edit game/ instead.\n(() => {
  const modules = {${sources.join(",\n")}};
  const cache = {};
  function require(name) {
    if (!cache[name]) {
      const module = { exports: {} };
      cache[name] = module;
      modules[name](module, module.exports, require);
    }
    return cache[name].exports;
  }
  globalThis.Flappy = { ...require("./canvas.cjs"), ...require("./i18n.cjs") };
})();\n`
const target = path.join(root, "web", "game.js")
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8").catch(() => "") !== bundle) {
    throw new Error("web/game.js is out of date. Run npm run build.")
  }
} else {
  await mkdir(path.dirname(target), { recursive: true })
  await writeFile(target, bundle)
}
