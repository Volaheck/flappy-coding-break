import { createRequire } from "node:module"
import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

const root = new URL("../", import.meta.url)
const require = createRequire(import.meta.url)
const { createGame, constants, clamp, hitRect } = require("../game/core.cjs")
const { messages, translate } = require("../game/i18n.cjs")
const header = "// Generated by scripts/build-claude.mjs from game/*.cjs.\n"
const outputs = new Map([
  ["adapters/claude/core.js", `${header}export const constants = ${JSON.stringify(constants, null, 2)}\nconst { ${Object.keys(constants).join(", ")} } = constants\nconst clamp = ${clamp.toString()}\nconst hitRect = ${hitRect.toString()}\nexport const createGame = ${createGame.toString()}\n`],
  ["adapters/claude/i18n.js", `${header}export const messages = ${JSON.stringify(messages, null, 2)}\nexport const translate = ${translate.toString()}\n`],
])

for (const [path, source] of outputs) {
  const target = new URL(path, root)
  if (process.argv.includes("--check")) {
    const current = await readFile(target, "utf8")
    if (current !== source) throw new Error(`Regenerate ${fileURLToPath(target)} with node scripts/build-claude.mjs`)
  } else {
    await writeFile(target, source)
  }
}
