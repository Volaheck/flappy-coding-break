import { createRequire } from "node:module"
import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

const root = new URL("../", import.meta.url)
const require = createRequire(import.meta.url)
const { createGame, constants, clamp } = require("../game/core.cjs")
const { messages, translate } = require("../game/i18n.cjs")
const { CITY, CLOUDS, DUCK_FRAMES } = require("../game/art.cjs")
const { THEME, phraseKind } = require("../game/theme.cjs")
const header = "// Generated by scripts/build-claude.mjs from game/*.cjs.\n"
const outputs = new Map([
  ["adapters/claude/core.js", `${header}export const constants = ${JSON.stringify(constants, null, 2)}\nconst { ${Object.keys(constants).join(", ")} } = constants\nconst clamp = ${clamp.toString()}\nexport const createGame = ${createGame.toString()}\n`],
  ["adapters/claude/i18n.js", `${header}export const messages = ${JSON.stringify(messages, null, 2)}\nexport const translate = ${translate.toString()}\n`],
  ["adapters/claude/art.js", `${header}export const CITY = ${JSON.stringify(CITY)}\nexport const CLOUDS = ${JSON.stringify(CLOUDS)}\nexport const DUCK_FRAMES = ${JSON.stringify(DUCK_FRAMES)}\n`],
  ["adapters/claude/theme.js", `${header}export const THEME = ${JSON.stringify(THEME, null, 2)}\nexport const phraseKind = ${phraseKind.toString()}\n`],
])

for (const [path, source] of outputs) {
  const target = new URL(path, root)
  if (process.argv.includes("--check")) {
    const current = await readFile(target, "utf8")
    if (current !== source) throw new Error(`Regenerate ${fileURLToPath(target)} with node scripts/build-claude.mjs`)
  } else {
    await writeFile(target, source)
  }
}
