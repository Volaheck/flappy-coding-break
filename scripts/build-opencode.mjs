import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import path from "node:path"

const root = fileURLToPath(new URL("../", import.meta.url))
const paths = ["game/constants.cjs", "game/core.cjs", "game/art.cjs", "game/theme.cjs", "game/canvas.cjs", "game/i18n.cjs", "adapters/opencode/gui.cjs"]
const sources = await Promise.all(paths.map(async (file) => {
  const source = await readFile(path.join(root, file), "utf8")
  return `${JSON.stringify(path.basename(file))}: (module, exports, require) => {\n${source}\n}`
}))
const bundle = `"use strict"
// Generated by scripts/build-opencode.mjs. Edit game/ and adapters/opencode/ instead.
module.exports = (() => {
  const externalRequire = require;
  const modules = {${sources.join(",\n")}};
  const cache = {};
  function load(name) {
    if (name === "@opencode/plugin/gui" || name === "solid-js") return externalRequire(name);
    const key = name.split("/").pop();
    if (!Object.hasOwn(modules, key)) throw new Error("Unknown bundled Flappy module: " + name);
    if (!cache[key]) {
      const module = { exports: {} };
      cache[key] = module;
      modules[key](module, module.exports, load);
    }
    return cache[key].exports;
  }
  return load("gui.cjs");
})();\n`
const target = path.join(root, "gui-experimental.cjs")
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8").catch(() => "") !== bundle) {
    throw new Error("gui-experimental.cjs is out of date. Run npm run build.")
  }
} else {
  await writeFile(target, bundle)
}
